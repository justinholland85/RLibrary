# Uses a vector function on a matrix using the standard Column-major order

#====================================================================================================#
# Lib.Flatwise  
#====================================================================================================#

Lib.Flatwise    <-  function(X, f, ...){
  
  return(array(f(c(X), ...), dim = dim(X)))
  
  
}